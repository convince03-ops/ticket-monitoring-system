-- Requestor ownership and private portal communications/files.
ALTER TABLE public."ticket-monitoring"
  ADD COLUMN IF NOT EXISTS requestor_email text;

UPDATE public."ticket-monitoring"
SET requestor_email = lower(trim(requestor_email))
WHERE requestor_email IS NOT NULL;

CREATE INDEX IF NOT EXISTS ticket_monitoring_requestor_email_idx
  ON public."ticket-monitoring" (lower(requestor_email))
  WHERE requestor_email IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.ticket_portal_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id text NOT NULL,
  ticket_number text NOT NULL,
  author_email text NOT NULL,
  author_name text NOT NULL,
  author_role text NOT NULL CHECK (author_role IN ('REQUESTOR', 'STAFF')),
  message_type text NOT NULL CHECK (message_type IN ('REPLY', 'INFORMATION', 'REVISION_REQUEST')),
  message text NOT NULL CHECK (length(message) BETWEEN 1 AND 5000),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ticket_portal_messages_ticket_created_idx
  ON public.ticket_portal_messages (ticket_id, created_at ASC);

CREATE TABLE IF NOT EXISTS public.ticket_portal_files (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id text NOT NULL,
  ticket_number text NOT NULL,
  uploaded_by_email text NOT NULL,
  file_name text NOT NULL,
  mime_type text NOT NULL,
  file_size bigint NOT NULL CHECK (file_size > 0 AND file_size <= 10485760),
  storage_path text NOT NULL UNIQUE,
  file_kind text NOT NULL CHECK (file_kind IN ('SUPPORTING', 'DELIVERABLE')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ticket_portal_files_ticket_kind_created_idx
  ON public.ticket_portal_files (ticket_id, file_kind, created_at DESC);

ALTER TABLE public.ticket_portal_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ticket_portal_files ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT ON public.ticket_portal_messages TO service_role;
GRANT SELECT, INSERT ON public.ticket_portal_files TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.ticket_portal_messages_id_seq TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.ticket_portal_files_id_seq TO service_role;

INSERT INTO storage.buckets (id, name, public, file_size_limit)
VALUES ('requestor-portal-files', 'requestor-portal-files', false, 10485760)
ON CONFLICT (id) DO UPDATE SET public = false, file_size_limit = 10485760;

