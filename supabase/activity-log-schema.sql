CREATE TABLE IF NOT EXISTS public.ticket_activity_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id text NOT NULL,
  ticket_number text NOT NULL,
  actor text NOT NULL DEFAULT 'System',
  action text NOT NULL,
  details text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ticket_activity_log_created_at_idx
  ON public.ticket_activity_log (created_at DESC);

CREATE INDEX IF NOT EXISTS ticket_activity_log_ticket_id_idx
  ON public.ticket_activity_log (ticket_id);

