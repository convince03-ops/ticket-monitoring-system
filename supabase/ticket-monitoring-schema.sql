-- Ensure the existing Supabase table has the columns the app expects.
-- This keeps the current live table name and adds the missing ticket fields.

CREATE TABLE IF NOT EXISTS public."ticket-monitoring" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public."ticket-monitoring"
  ADD COLUMN IF NOT EXISTS ticket_number text,
  ADD COLUMN IF NOT EXISTS description text,
  ADD COLUMN IF NOT EXISTS department text,
  ADD COLUMN IF NOT EXISTS requestor text,
  ADD COLUMN IF NOT EXISTS material text,
  ADD COLUMN IF NOT EXISTS designer text,
  ADD COLUMN IF NOT EXISTS ticket_request_date timestamptz,
  ADD COLUMN IF NOT EXISTS date_received_by_artist timestamptz,
  ADD COLUMN IF NOT EXISTS working_days integer DEFAULT 0,
  ADD COLUMN IF NOT EXISTS deadline timestamptz,
  ADD COLUMN IF NOT EXISTS date_of_submission timestamptz,
  ADD COLUMN IF NOT EXISTS count integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS ticket_level text,
  ADD COLUMN IF NOT EXISTS status text DEFAULT 'OPEN',
  ADD COLUMN IF NOT EXISTS remarks text,
  ADD COLUMN IF NOT EXISTS others text,
  ADD COLUMN IF NOT EXISTS source_name text,
  ADD COLUMN IF NOT EXISTS source_row integer;

DROP INDEX IF EXISTS public.ticket_monitoring_ticket_number_key;

CREATE UNIQUE INDEX IF NOT EXISTS ticket_monitoring_source_row_key
  ON public."ticket-monitoring" (source_name, source_row)
  WHERE source_name IS NOT NULL AND source_row IS NOT NULL;
